"""Generate the addon's disenchant table from ahsync/engine/de_table.py (SPEC §4.5).

Usage: python tools/gen_disenchant_data.py

Writes addon/AHProfit/Data/Disenchant.lua as one compact string (Lua constant
limits; CLAUDE.md data files), in DE_TABLE's row order, so Python and Lua walk
the same rows in the same order. tests/addon/Engine/Disenchant_spec.lua checks
that the generated file matches the Python table.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ahsync.engine.de_table import DE_TABLE  # noqa: E402

OUT = ROOT / "addon" / "AHProfit" / "Data" / "Disenchant.lua"


def encode(table: tuple[tuple, ...]) -> str:
    """Encode DE rows as "quality|kind|lo|hi|skill|key:chance:min:max,...;...".

    Args:
        table: DE_TABLE.

    Returns:
        The compact string; floats use repr, which Lua parses to the same double.
    """
    rows = []
    for quality, kind, lo, hi, skill, outcomes in table:
        mats = ",".join(f"{key}:{chance!r}:{qmin}:{qmax}" for key, chance, qmin, qmax in outcomes)
        rows.append(f"{quality}|{kind}|{lo}|{hi}|{skill}|{mats}")
    return ";".join(rows)


def render(table: tuple[tuple, ...]) -> str:
    """The Lua data file.

    Args:
        table: DE_TABLE.

    Returns:
        Lua source setting AHProfit.Data.DISENCHANT.
    """
    return ("-- Generated by tools/gen_disenchant_data.py from ahsync/engine/de_table.py. Do not edit.\n"
            "-- UNVERIFIED for Forever (SPEC §6 item 3): Classic Era values.\n"
            "AHProfit.Data = AHProfit.Data or {}\n"
            f'AHProfit.Data.DISENCHANT = "{encode(table)}"\n')


def main() -> int:
    """Write the data file.

    Returns:
        Process exit code: 0.
    """
    OUT.write_text(render(DE_TABLE), encoding="utf-8", newline="\n")
    print(f"gen_disenchant_data: {len(DE_TABLE)} rows -> {OUT.relative_to(ROOT).as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
