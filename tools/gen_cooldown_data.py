"""Generate the addon's cooldown catalog from AHSync's (SPEC §3.4F.1, §4.5, CD3).

Usage: python tools/gen_cooldown_data.py          # write addon/AHProfit/Data/Cooldowns.lua
       python tools/gen_cooldown_data.py --check  # exit 1, naming the first differing spell, when it is stale

The curated list lives in ahsync/data/cooldown_catalog.json. The addon ships the same rows, with the
same version, as addon/AHProfit/Data/Cooldowns.lua, so every user has the full list with or without
AHSync. The file is generated, never edited by hand, and tests/tools/test_gen_cooldown_data.py fails
when it no longer matches the JSON. A catalog with a row engine.cooldowns would skip is refused, so a
bad row never ships.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ahsync.engine.cooldowns import CooldownRecipe, catalog  # noqa: E402
from ahsync.recommend.cooldowns_page import CATALOG_PATH, read_catalog  # noqa: E402

OUT = ROOT / "addon" / "AHProfit" / "Data" / "Cooldowns.lua"
HEADER = ("-- Generated by tools/gen_cooldown_data.py from ahsync/data/cooldown_catalog.json. Do not edit.\n"
          "-- The curated cooldown catalog (SPEC §3.4F.1), one string per spell, by spell id:\n"
          "-- \"spell;name;profession;skill;cooldownS;group;product;yieldMin;yieldMax;reagents;tool;toolUse\",\n"
          "-- reagents \"key,count/key,count\" by key; an empty group or tool = none; toolUse 1 = the tool's\n"
          "-- Use spell (no recipe to learn), empty = a recipe.\n")


def row_text(recipe: CooldownRecipe) -> str:
    """One catalog row as the addon's compact string.

    Args:
        recipe: A validated catalog row.

    Returns:
        "spell;name;profession;skill;cooldownS;group;product;yieldMin;yieldMax;reagents;tool;toolUse".

    Raises:
        ValueError: when the name or group holds a ";", "/", "," or a quote, which would break the string.
    """
    for text in (recipe.name, recipe.group or ""):
        if any(c in text for c in ';/,"\\'):
            raise ValueError(f"spell {recipe.spell}: {text!r} holds a separator")
    reagents = "/".join(f"{key},{count}" for key, count in recipe.reagents)
    fields = (recipe.spell, recipe.name, recipe.profession, recipe.skill, recipe.cooldown_s, recipe.group or "",
              recipe.product, recipe.yield_min, recipe.yield_max, reagents, recipe.tool or "",
              1 if recipe.tool_use else "")
    return ";".join(str(f) for f in fields)


def render(path: Path = CATALOG_PATH) -> str:
    """The whole Lua file for a catalog.

    Args:
        path: The catalog JSON.

    Returns:
        The file's text.

    Raises:
        ValueError: when the file can't be read, has no version, or has a row engine.cooldowns skips.
    """
    rows, version, unread = read_catalog(path)
    if unread or version is None:
        raise ValueError(unread or "the catalog has no version")
    kept, skipped = catalog(rows)
    if skipped:
        raise ValueError(f"{len(skipped)} row(s) would be skipped: {'; '.join(skipped)}")
    body = "".join(f'  "{row_text(r)}",\n' for r in kept)
    return (f"{HEADER}AHProfit.Data = AHProfit.Data or {{}}\nAHProfit.Data.COOLDOWNS_VERSION = {version}\n"
            f"AHProfit.Data.COOLDOWNS = {{\n{body}}}\n")


def first_difference(expected: str, actual: str) -> str:
    """Name the first row where a stale Lua file differs from the JSON (CD3).

    Args:
        expected: render()'s text.
        actual: The Lua file as it is.

    Returns:
        "" when they match; else e.g. "spell 17187 differs" or "the version differs".
    """
    if expected == actual:
        return ""
    want, have = expected.splitlines(), actual.splitlines()
    for i in range(max(len(want), len(have))):
        line_want = want[i] if i < len(want) else ""
        line_have = have[i] if i < len(have) else ""
        if line_want != line_have:
            row = line_want or line_have
            if "COOLDOWNS_VERSION" in row:
                return "the version differs"
            spell = row.strip().lstrip('"').split(";", 1)[0]
            return f"spell {spell} differs" if spell.isdigit() else f"line {i + 1} differs"
    return "the line endings differ"


def main(argv: list[str]) -> int:
    """Write the Lua file, or check it with --check.

    Args:
        argv: Command-line arguments after the program name.

    Returns:
        0 on success; 1 when --check finds the file stale (the reason goes to stderr).
    """
    text = render()
    if "--check" in argv:
        actual = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.exists() else ""
        why = first_difference(text, actual)
        if why:
            print(f"Data/Cooldowns.lua is stale ({why}): run python tools/gen_cooldown_data.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
