"""Install the addon into the WoW client's AddOns folder (SPEC §3.5, §5).

Usage: python tools/deploy.py [--wow-path PATH] [--dry-run]

- `addon/AHProfit` is mirrored into `<wow>/Interface/AddOns/AHProfit`: changed
  files are copied, and files no longer in the repo are removed (only inside
  that folder).
- `addon/AHProfit_Data` gets its .toc copied, but its `MarketIntelligence.lua` and
  `PortfolioPlan.lua` placeholders only when none exists, so files generated by
  AHSync are never overwritten.
- WoW only loads addon files that existed when the client started. When a file
  is new to the client, the script says to restart WoW; otherwise /reload is enough.

The WoW path comes from --wow-path, else `wow_path` in config.toml, else the
SPEC §3.6 default.
"""
from __future__ import annotations

import argparse
import filecmp
import os
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from ahsync.config import Config, load_config  # noqa: E402  (needs ROOT on sys.path)

ADDON = ROOT / "addon" / "AHProfit"
DATA_ADDON = ROOT / "addon" / "AHProfit_Data"
GENERATED = ("MarketIntelligence.lua", "PortfolioPlan.lua")   # written by AHSync


@dataclass
class Plan:
    """What a deploy will change, so it can be shown before (or instead of) doing it."""

    copy: list[tuple[Path, Path]] = field(default_factory=list)    # (source, target)
    remove: list[Path] = field(default_factory=list)
    new_to_client: list[Path] = field(default_factory=list)        # targets that didn't exist before
    kept_generated: list[Path] = field(default_factory=list)


def wow_path_from_config(arg: str | None) -> Path:
    """Decide which WoW client folder to deploy into.

    Args:
        arg: The --wow-path value, or None.

    Returns:
        The client folder (the one holding Interface/ and WTF/).
    """
    if arg:
        return Path(arg)
    config_file = ROOT / "config.toml"
    if config_file.exists():
        return Path(load_config(config_file, os.environ, Path.home()).wow_path)
    return Path(Config().wow_path)


def plan_mirror(source: Path, target: Path, plan: Plan) -> None:
    """Add the copies and removals that make target an exact copy of source.

    Args:
        source: A folder in the repo.
        target: The matching folder under Interface/AddOns (may not exist yet).
        plan: Collects the changes.
    """
    wanted = {p.relative_to(source) for p in source.rglob("*") if p.is_file()}
    for rel in sorted(wanted):
        src, dst = source / rel, target / rel
        if not dst.exists():
            plan.copy.append((src, dst))
            plan.new_to_client.append(dst)
        elif not filecmp.cmp(src, dst, shallow=False):
            plan.copy.append((src, dst))
    if target.exists():
        for existing in sorted(p for p in target.rglob("*") if p.is_file()):
            if existing.relative_to(target) not in wanted:
                plan.remove.append(existing)


def plan_data_addon(source: Path, target: Path, plan: Plan) -> None:
    """Add the copies for AHProfit_Data, never replacing an existing generated file.

    Args:
        source: addon/AHProfit_Data in the repo.
        target: Interface/AddOns/AHProfit_Data.
        plan: Collects the changes.
    """
    for src in sorted(p for p in source.iterdir() if p.is_file()):
        dst = target / src.name
        if src.name in GENERATED and dst.exists():
            plan.kept_generated.append(dst)
            continue
        if not dst.exists():
            plan.copy.append((src, dst))
            plan.new_to_client.append(dst)
        elif not filecmp.cmp(src, dst, shallow=False):
            plan.copy.append((src, dst))


def apply(plan: Plan) -> None:
    """Carry out a plan: copy files, then remove stale ones and empty folders.

    Args:
        plan: From plan_mirror and plan_data_addon.

    Raises:
        PermissionError: If the AddOns folder isn't writable (e.g. needs admin rights).
    """
    for src, dst in plan.copy:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
    for stale in plan.remove:
        stale.unlink()
        parent = stale.parent
        while parent.name != "AddOns" and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent


def main() -> int:
    """Parse arguments, show what changes, apply it unless --dry-run, and say whether to restart WoW.

    Returns:
        Process exit code: 0 on success, 1 when the WoW folder is wrong or not writable.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--wow-path", help="WoW client folder, e.g. ...\\World of Warcraft\\_classic_beta_")
    parser.add_argument("--dry-run", action="store_true", help="show the changes without making them")
    args = parser.parse_args()

    wow = wow_path_from_config(args.wow_path)
    addons = wow / "Interface" / "AddOns"
    if not addons.is_dir():
        print(f"deploy: no Interface/AddOns under {wow}. Pass --wow-path or set wow_path in config.toml.")
        return 1

    plan = Plan()
    plan_mirror(ADDON, addons / ADDON.name, plan)
    plan_data_addon(DATA_ADDON, addons / DATA_ADDON.name, plan)

    for src, dst in plan.copy:
        print(f"  {'new ' if dst in plan.new_to_client else 'copy'}  {dst.relative_to(addons)}")
    for stale in plan.remove:
        print(f"  del   {stale.relative_to(addons)}")
    for kept in plan.kept_generated:
        print(f"  keep  {kept.relative_to(addons)} (already installed; never overwritten)")
    if not plan.copy and not plan.remove:
        print(f"deploy: already up to date in {addons}")
        return 0
    if args.dry_run:
        print("deploy: dry run, nothing changed")
        return 0

    try:
        apply(plan)
    except PermissionError as error:
        print(f"deploy: can't write to {addons} ({error.strerror}). Run the terminal as administrator, "
              "or give your user write access to the WoW folder.")
        return 1
    changed = len(plan.copy) + len(plan.remove)
    if plan.new_to_client or plan.remove:
        print(f"deploy: {changed} change(s). Files were added or removed: RESTART WoW (a /reload won't see them).")
    else:
        print(f"deploy: {changed} change(s). Type /reload in game.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
