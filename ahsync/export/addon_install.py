"""Install the bundled addon into the WoW client's AddOns folder (SPEC §3.7.7; `tools/deploy.py` uses it too).

- `AHProfit/` is mirrored: changed files are copied, and files no longer in the bundle are
  removed (only inside that folder).
- `AHProfit_Data/` gets its .toc, but its `MarketIntelligence.lua` and `PortfolioPlan.lua`
  placeholders only when none exists, so files generated by AHSync are never overwritten (SPEC §3.5).
- WoW loads only files that existed when the client started: an install that adds or removes a
  file needs a WoW restart, one that only changes files a /reload.

Before any copy the folder and a write probe are checked, and each file is written to a temp
name and renamed, so a refused or interrupted install never leaves a half-written file (FM49).
"""
from __future__ import annotations

import filecmp
import os
import shutil
import uuid
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path

from ahsync.engine.app_view import addon_text

CODE_ADDON = "AHProfit"
DATA_ADDON = "AHProfit_Data"
GENERATED = ("MarketIntelligence.lua", "PortfolioPlan.lua")   # written by AHSync
TEMP_SUFFIX = ".ahsync-tmp"


@dataclass
class Plan:
    """What an install will change, so it can be shown before (or instead of) doing it."""

    copy: list[tuple[Path, Path]] = field(default_factory=list)    # (source, target)
    remove: list[Path] = field(default_factory=list)
    new_to_client: list[Path] = field(default_factory=list)        # targets that didn't exist before
    kept_generated: list[Path] = field(default_factory=list)


@dataclass(frozen=True)
class AddonResult:
    """What an install did, and the Addon line that says so (SPEC §3.7.7)."""

    outcome: str          # "installed" | "no_addons" | "not_writable"
    added: int            # files new to the client
    removed: int          # stale files deleted
    changed: int          # existing files replaced
    line: dict            # {"text", "class"} from engine/app_view.addon_text

    @property
    def restart_wow(self) -> bool:
        """Whether WoW must restart to load the install (files were added or removed).

        Returns:
            True when a file was added or removed.
        """
        return bool(self.added or self.removed)


def plan_mirror(source: Path, target: Path, plan: Plan) -> None:
    """Add the copies and removals that make target an exact copy of source.

    Args:
        source: A folder of the bundle (or the repo).
        target: The matching folder under Interface/AddOns (may not exist yet).
        plan: Collects the changes.
    """
    wanted = {p.relative_to(source) for p in source.rglob("*") if p.is_file()}
    for rel in sorted(wanted):
        src, dst = source / rel, target / rel
        if not dst.exists():
            plan.copy.append((src, dst))
            plan.new_to_client.append(dst)
        elif not filecmp.cmp(src, dst, shallow=False):
            plan.copy.append((src, dst))
    if target.exists():
        for existing in sorted(p for p in target.rglob("*") if p.is_file()):
            if existing.relative_to(target) not in wanted:
                plan.remove.append(existing)


def plan_data_addon(source: Path, target: Path, plan: Plan) -> None:
    """Add the copies for AHProfit_Data, never replacing an existing generated file.

    Args:
        source: The bundle's AHProfit_Data.
        target: Interface/AddOns/AHProfit_Data.
        plan: Collects the changes.
    """
    for src in sorted(p for p in source.iterdir() if p.is_file()):
        dst = target / src.name
        if src.name in GENERATED and dst.exists():
            plan.kept_generated.append(dst)
            continue
        if not dst.exists():
            plan.copy.append((src, dst))
            plan.new_to_client.append(dst)
        elif not filecmp.cmp(src, dst, shallow=False):
            plan.copy.append((src, dst))


def copy_atomically(src: Path, dst: Path, copy: Callable[[Path, Path], object] = shutil.copy2) -> None:
    """Copy a file to a temp name beside its target, then rename it over the target (FM49).

    Args:
        src: The bundled file.
        dst: Its place under AddOns.
        copy: Copies one file (shutil.copy2; a fake that fails part-way in tests).

    Raises:
        OSError: When the copy or the rename fails; the temp file is removed and dst is untouched.
    """
    dst.parent.mkdir(parents=True, exist_ok=True)
    temp = dst.with_name(dst.name + TEMP_SUFFIX)
    try:
        copy(src, temp)
        os.replace(temp, dst)
    except BaseException:
        temp.unlink(missing_ok=True)
        raise


def apply(plan: Plan, copy: Callable[[Path, Path], object] = shutil.copy2) -> None:
    """Carry out a plan: copy files (temp name + rename), then remove stale ones and empty folders.

    Args:
        plan: From plan_mirror and plan_data_addon.
        copy: Copies one file (see copy_atomically).

    Raises:
        PermissionError: If the AddOns folder isn't writable (e.g. needs admin rights).
    """
    for src, dst in plan.copy:
        copy_atomically(src, dst, copy)
    for stale in plan.remove:
        stale.unlink()
        parent = stale.parent
        while parent.name != "AddOns" and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent


def can_write(folder: Path) -> bool:
    """The write probe: create a temp file in the folder and remove it (FM49).

    Args:
        folder: Interface/AddOns.

    Returns:
        True when the file could be created (and was removed again).
    """
    probe = folder / f".ahsync-probe-{uuid.uuid4().hex}"
    try:
        probe.write_bytes(b"")
        probe.unlink()
    except OSError:
        return False
    return True


def install_addon(bundle_addon_dir: Path, wow_path: str | Path,
                  probe: Callable[[Path], bool] = can_write,
                  copy: Callable[[Path, Path], object] = shutil.copy2) -> AddonResult:
    """Install the bundled addon into `<wow_path>/Interface/AddOns` (SPEC §3.7.7; DR3, DR4, FM49).

    Args:
        bundle_addon_dir: The bundle's addon folder, holding AHProfit/ and AHProfit_Data/.
        wow_path: The WoW client folder (holding Interface/ and WTF/).
        probe: Whether AddOns can be written (can_write; a refusing fake in tests).
        copy: Copies one file (shutil.copy2).

    Returns:
        The counts and the Addon line. Nothing is copied when AddOns is missing or not writable;
        never raises for a filesystem failure, so the app runs on.
    """
    addons = Path(wow_path) / "Interface" / "AddOns"
    if not addons.is_dir():
        return AddonResult("no_addons", 0, 0, 0, addon_text("no_addons", str(wow_path)))
    if not probe(addons):
        return AddonResult("not_writable", 0, 0, 0, addon_text("not_writable"))
    plan = Plan()
    plan_mirror(bundle_addon_dir / CODE_ADDON, addons / CODE_ADDON, plan)
    plan_data_addon(bundle_addon_dir / DATA_ADDON, addons / DATA_ADDON, plan)
    try:
        apply(plan, copy)
    except OSError:
        return AddonResult("not_writable", 0, 0, 0, addon_text("not_writable"))
    added, removed = len(plan.new_to_client), len(plan.remove)
    changed = len(plan.copy) - added
    line = addon_text("installed", str(wow_path), added + removed, changed)
    return AddonResult("installed", added, removed, changed, line)
